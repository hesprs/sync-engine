import { documentSplitter, codeSplitter, proseSplitter } from '@/utils/splitters';
import { test, expect } from 'bun:test';

test('documentSplitter', () => {
	const { joints, tokens, splitters } = documentSplitter(`# Title

---

## H2

There are four pieces of trash.
Dirty.

\`\`\`TypeScript
const complaint = 'These are trash.';
console.log(complaint);
\`\`\``);
	expect(joints).toStrictEqual(['\n\n', '\n\n', '\n\n', '\n', '\n\n', '\n', '\n']);
	expect(tokens).toStrictEqual([
		'# Title',
		'---',
		'## H2',
		'There are four pieces of trash.',
		'Dirty.',
		'```TypeScript',
		`const complaint = 'These are trash.';
console.log(complaint);`,
		'```',
	]);
	expect(splitters.length).toBe(tokens.length);
});

test('codeSplitter', () => {
	const { tokens, joints, splitters } = codeSplitter(`const complaint = 'These are trash.';
console.log(complaint);

for (const a of [1, 2, 3]) console.log(a);`);
	expect(tokens).toStrictEqual([
		`const complaint = 'These are trash.';`,
		'console.log(complaint);',
		'for (const a of [1, 2, 3]) console.log(a);',
	]);
	expect(joints).toStrictEqual(['\n', '\n\n']);
	expect(splitters.length).toBe(tokens.length);
});

